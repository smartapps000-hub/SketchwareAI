package com.sketchware.ai.editor;

import com.besome.sketch.beans.BlockBean;

import java.util.ArrayList;
import java.util.HashMap;
import java.util.HashSet;
import java.util.List;
import java.util.Map;
import java.util.Set;

/**
 * Marks a throw-away generation of an activity for the Java editor (v1.8.8), the way the build's source map marks
 * blocks ({@link com.sketchware.ai.sourcemap.SourceMapMarkers}), plus a pair of markers around every event body, so
 * an empty event has a place too. While a session runs on this thread, the code generator's block lists go through
 * {@link #wrap}: it hands back marked copies (marker blocks are "add source directly" blocks whose code is a comment).
 * The project's own lists are never changed. {@link EditMap#extract} takes the markers out again and proves that the
 * result is the normal generation.
 */
public final class EditMarkers {

    static final String PREFIX = "/*@SWED";
    static final String SUFFIX = "@*/";

    /** Where a statement block sits: its parent block (null at the top of the event) and which stack of it. */
    public static final class BlockInfo {
        public String id;
        public String opCode;
        /** Null for the event's top-level chain. */
        public String parentId;
        /** 0 = the event's top chain, 1 / 2 = the parent's first / second stack. */
        public int stack;
    }

    /** One event body (event, onCreate's initializeLogic, MoreBlock, adapter onBindCustomView) of the generation. */
    public static final class Event {
        public int index;
        /** "event", "onCreate", "moreBlock" or "adapter" (as the build's source map). */
        public String kind;
        public String targetId;
        public String eventName;
        /** False when the blocks couldn't be marked (ids not numbers, a loop): edits there are refused. */
        public boolean marked = true;
        public final Map<String, BlockInfo> blocks = new HashMap<>();

        /** The key of the event's blocks in the project data (eC.d): "button1_onClick", "onCreate_initializeLogic" ... */
        public String key() {
            switch (kind) {
                case "onCreate":
                    return "onCreate_initializeLogic";
                case "moreBlock":
                    return targetId + "_moreBlock";
                case "adapter":
                    return targetId + "_onBindCustomView";
                default:
                    return targetId + "_" + eventName;
            }
        }
    }

    private static final ThreadLocal<List<Event>> SESSION = new ThreadLocal<>();

    private EditMarkers() {
    }

    public static void begin() {
        SESSION.set(new ArrayList<Event>());
    }

    public static List<Event> end() {
        List<Event> events = SESSION.get();
        SESSION.remove();
        return events == null ? new ArrayList<Event>() : events;
    }

    public static boolean active() {
        return SESSION.get() != null;
    }

    /**
     * Code of an event without blocks. Outside a session "" (what the generator always wrote); inside one, the event's
     * two markers, generated by the generator itself.
     */
    public static String emptyEventLogic(String activityName, a.a.a.jq buildConfig, String eventName, String targetId) {
        if (!active()) return "";
        return new a.a.a.Fx(activityName, buildConfig, eventName, wrap(new ArrayList<BlockBean>(), "event", targetId, eventName)).a();
    }

    /**
     * @return {@code blocks} itself outside a session; inside one, a marked copy for the code generator: the event's
     * begin marker first (the generator starts at the first block of the list), then the blocks, each between its own
     * pair of markers, then the event's end marker
     */
    public static ArrayList<BlockBean> wrap(ArrayList<BlockBean> blocks, String kind, String targetId, String eventName) {
        List<Event> session = SESSION.get();
        if (session == null) return blocks;
        Event event = new Event();
        event.index = session.size();
        event.kind = kind;
        event.targetId = targetId;
        event.eventName = eventName;
        session.add(event);
        try {
            ArrayList<BlockBean> marked = mark(blocks == null ? new ArrayList<BlockBean>() : blocks, event);
            if (marked != null) return marked;
        } catch (RuntimeException ignored) {
            // falls through: the event is generated as it is, without markers
        }
        event.marked = false;
        event.blocks.clear();
        return blocks;
    }

    private static ArrayList<BlockBean> mark(ArrayList<BlockBean> blocks, Event event) {
        Map<Integer, BlockBean> copies = new HashMap<>();
        int maxId = 0;
        for (BlockBean block : blocks) {
            int id;
            try {
                id = Integer.parseInt(block.id);
            } catch (NumberFormatException e) {
                return null;
            }
            if (copies.containsKey(id)) return null;
            copies.put(id, block.clone());
            maxId = Math.max(maxId, id);
        }
        int[] nextId = {maxId + 1};
        List<BlockBean> markers = new ArrayList<>();
        BlockBean eventBegin = marker(nextId[0]++, PREFIX + "[" + event.index + SUFFIX);
        BlockBean eventEnd = marker(nextId[0]++, PREFIX + "]" + event.index + SUFFIX);
        ArrayList<BlockBean> ordered = new ArrayList<>(blocks.size() * 3 + 2);
        ordered.add(eventBegin);
        if (blocks.isEmpty()) {
            eventBegin.nextBlock = Integer.parseInt(eventEnd.id);
        } else {
            Set<Integer> visited = new HashSet<>();
            BlockBean[] lastEnd = new BlockBean[1];
            int head = chain(Integer.parseInt(blocks.get(0).id), copies, visited, markers, nextId, event, null, 0, 0, lastEnd);
            if (head < 0 || lastEnd[0] == null) return null;
            eventBegin.nextBlock = head;
            lastEnd[0].nextBlock = Integer.parseInt(eventEnd.id);
            for (BlockBean block : blocks) ordered.add(copies.get(Integer.parseInt(block.id)));
            ordered.addAll(markers);
        }
        ordered.add(eventEnd);
        return ordered;
    }

    /**
     * Marks the chain that starts at block {@code id}.
     *
     * @param lastEnd receives the end marker of the chain's last block
     * @return the id the chain starts with now (its first block's begin marker), or -1 if the blocks don't form a
     * clean chain
     */
    private static int chain(int id, Map<Integer, BlockBean> copies, Set<Integer> visited, List<BlockBean> markers,
                             int[] nextId, Event event, String parentId, int stack, int depth, BlockBean[] lastEnd) {
        int chainHead = -1;
        BlockBean previousEnd = null;
        int current = id;
        while (current >= 0) {
            BlockBean block = copies.get(current);
            if (block == null || !visited.add(current) || depth > 200) return -1;
            BlockInfo info = new BlockInfo();
            info.id = block.id;
            info.opCode = block.opCode;
            info.parentId = parentId;
            info.stack = stack;
            event.blocks.put(block.id, info);
            BlockBean begin = marker(nextId[0]++, PREFIX + "+" + event.index + ":" + block.id + SUFFIX);
            BlockBean end = marker(nextId[0]++, PREFIX + "-" + event.index + ":" + block.id + SUFFIX);
            markers.add(begin);
            markers.add(end);
            begin.nextBlock = current;
            if (previousEnd != null) previousEnd.nextBlock = Integer.parseInt(begin.id);
            else chainHead = Integer.parseInt(begin.id);
            BlockBean[] ignored = new BlockBean[1];
            if (block.subStack1 >= 0) {
                int head = chain(block.subStack1, copies, visited, markers, nextId, event, block.id, 1, depth + 1, ignored);
                if (head < 0) return -1;
                block.subStack1 = head;
            }
            if (block.subStack2 >= 0) {
                int head = chain(block.subStack2, copies, visited, markers, nextId, event, block.id, 2, depth + 1, ignored);
                if (head < 0) return -1;
                block.subStack2 = head;
            }
            int next = block.nextBlock;
            block.nextBlock = Integer.parseInt(end.id);
            previousEnd = end;
            current = next;
        }
        lastEnd[0] = previousEnd;
        return chainHead;
    }

    static BlockBean marker(int id, String comment) {
        BlockBean marker = new BlockBean();
        marker.id = String.valueOf(id);
        marker.spec = "add source directly %s.inputOnly";
        marker.type = " ";
        marker.typeName = "";
        marker.opCode = "addSourceDirectly";
        marker.color = 0xff5cb722;
        marker.parameters.add(comment);
        return marker;
    }
}
